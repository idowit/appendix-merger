export function t(language: InterfaceLanguage) {
  return copy[language];
}

const errorKeys = {
  UNSUPPORTED_FORMAT: "errorUnsupportedFormat",
  ENCRYPTED_PDF: "errorEncryptedPdf",
  INVALID_PDF: "errorInvalidPdf",
  EMPTY_FILE: "errorEmptyFile",
  SIZE_LIMIT_EXCEEDED: "errorSizeLimit",
  INVALID_ARCHIVE: "errorInvalidArchive",
  UNSUPPORTED_VERSION: "errorUnsupportedVersion",
  MISSING_DOCUMENT: "errorMissingDocument",
  PDF_GENERATION_FAILED: "errorGeneration",
} as const;

export function translateNotice(language: InterfaceLanguage, notice: string): string {
  const labels = t(language);
  return notice.split(" · ").map((part) => {
    const separator = part.lastIndexOf(": ");
    const filename = separator >= 0 ? part.slice(0, separator) : "";
    const code = (separator >= 0 ? part.slice(separator + 2) : part) as keyof typeof errorKeys;
    const key = errorKeys[code];
    const message = key ? labels[key] : labels.errorUnknown;
    return filename ? `${filename}: ${message}` : message;
  }).join(" · ");
}
